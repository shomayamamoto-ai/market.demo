      <li>SNSを4週間やめると、幸福感が0.09標準偏差上がり、ニュースの知識は0.19標準偏差下がった(Facebook、NBER w25514)。SNSの利用の約31%は「やめたいのにやめられない」ことによるもの(NBER w28936)。</li>
