      <li>10〜17歳の平日のネットの利用時間は平均326.6分(2023年度は296.9分)。17歳は427分。高校生の26.2%が「使いすぎて勉強や睡眠に影響した」と答えた(こども家庭庁 令和7年度)。</li>
